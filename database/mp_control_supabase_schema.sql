-- 3. TRIGGERS (reglas de negocio entre tablas: controles 62, 67 y 73 del Excel)
create or replace function fn_uso_ot_mismo_equipo() returns trigger language plpgsql as $$
begin
  if new.ot is not null and exists (select 1 from ordenes_trabajo o where o.ot = new.ot and o.codigo_equipo <> new.codigo_equipo) then
    raise exception 'La OT % no corresponde al equipo %', new.ot, new.codigo_equipo;
  end if;
  return new;
end $$;
drop trigger if exists trg_uso_ot_mismo_equipo on uso_repuestos;
create trigger trg_uso_ot_mismo_equipo before insert or update on uso_repuestos for each row execute function fn_uso_ot_mismo_equipo();

create or replace function fn_recepcion_equipo_contrato() returns trigger language plpgsql as $$
begin
  if new.num_contrato is not null and exists (select 1 from contratos c where c.num_contrato = new.num_contrato and c.codigo_equipo <> new.codigo_equipo) then
    raise exception 'El equipo % no es el del contrato %', new.codigo_equipo, new.num_contrato;
  end if;
  return new;
end $$;
drop trigger if exists trg_recepcion_equipo_contrato on recepciones;
create trigger trg_recepcion_equipo_contrato before insert or update on recepciones for each row execute function fn_recepcion_equipo_contrato();

create or replace function fn_ot_una_preventiva() returns trigger language plpgsql as $$
begin
  if new.estado <> 'Completada'
     and exists (select 1 from cat_tipos_trabajo t where t.tipo_trabajo = new.tipo_trabajo and t.es_preventiva = 'Sí')
     and exists (select 1 from ordenes_trabajo o join cat_tipos_trabajo t on t.tipo_trabajo = o.tipo_trabajo
                 where o.codigo_equipo = new.codigo_equipo and o.estado <> 'Completada' and t.es_preventiva = 'Sí' and o.ot <> new.ot) then
    raise exception 'El equipo % ya tiene una OT preventiva abierta', new.codigo_equipo;
  end if;
  return new;
end $$;
drop trigger if exists trg_ot_una_preventiva on ordenes_trabajo;
create trigger trg_ot_una_preventiva before insert or update on ordenes_trabajo for each row execute function fn_ot_una_preventiva();

-- 4. VISTAS (lo que se puede calcular no se guarda; réplica de las hojas Vista_ del Excel)
create or replace view vista_contratos with (security_invoker = true) as
select s.*,
  case when s.estado <> 'Vigente' then s.estado
       when s.termino_actual < now() then 'Vencido'
       when s.termino_actual - now() <= make_interval(days => (select valor::int from config where parametro = 'dias_aviso_vencimiento')) then 'Por vencer'
       else 'Vigente' end as estado_operativo,
  case when s.estado = 'Vigente' and s.termino_actual < now() then floor(extract(epoch from (now() - s.termino_actual)) / 86400)::int else 0 end as dias_atraso
from (
  select c.num_contrato, c.codigo_equipo, e.nombre as equipo_nombre, cl.nombre as cliente, c.destino,
         c.fecha_salida, c.fecha_termino_original as termino_original,
         coalesce(x.dias, 0)::int as dias_extendidos,
         c.fecha_termino_original + make_interval(days => coalesce(x.dias, 0)::int) as termino_actual,
         c.estado, c.registrado_por
  from contratos c
  left join equipos e on e.codigo_equipo = c.codigo_equipo
  left join clientes cl on cl.id_cliente = c.id_cliente
  left join (select num_contrato, sum(dias) as dias from extensiones_contrato group by num_contrato) x on x.num_contrato = c.num_contrato
) s;

create or replace view vista_recepciones with (security_invoker = true) as
select r.id_recepcion, r.codigo_equipo, e.nombre as equipo_nombre, r.fecha_llegada_fisica, r.fecha_registro,
       round(extract(epoch from (r.fecha_registro - r.fecha_llegada_fisica)) / 60)::int as demora_min,
       r.estado_fisico, coalesce(ef.requiere_revision, 'No') as requiere_revision, r.horometro_h,
       case when r.foto_url is null then 'No' else 'Sí' end as tiene_foto,
       c.codigo_equipo as equipo_del_contrato,
       case when r.num_contrato is null then null when c.codigo_equipo = r.codigo_equipo then 'Sí' else 'No' end as coincide_equipo,
       r.registrado_por
from recepciones r
left join equipos e on e.codigo_equipo = r.codigo_equipo
left join cat_estados_fisicos ef on ef.estado_fisico = r.estado_fisico
left join contratos c on c.num_contrato = r.num_contrato;

create or replace view vista_uso with (security_invoker = true) as
select u.id_uso, u.fecha_hora, r.nombre as repuesto, u.cantidad,
       case when public.mp_rol() = 'Jefe' then coalesce(u.precio_unitario_clp, r.precio_unitario_clp, 0) end as precio_unitario_clp,
       case when public.mp_rol() = 'Jefe' then u.cantidad * coalesce(u.precio_unitario_clp, r.precio_unitario_clp, 0) end as subtotal_clp,
       u.codigo_equipo, coalesce(u.ot, 'sin OT') as ot, case when u.ot is null then 0 else 1 end as con_ot,
       (extract(year from u.fecha_hora at time zone 'America/Santiago') * 100 + extract(month from u.fecha_hora at time zone 'America/Santiago'))::int as mes_clave,
       u.registrado_por, o.codigo_equipo as equipo_de_la_ot,
       case when u.ot is null then null when o.codigo_equipo = u.codigo_equipo then 'Sí' else 'No' end as coincide_equipo
from uso_repuestos u
left join repuestos r on r.id_repuesto = u.id_repuesto
left join ordenes_trabajo o on o.ot = u.ot;

create or replace view vista_inventario with (security_invoker = true) as
select z.*,
  greatest(0, z.stock_minimo - z.proyectado) as sugerido_pedir,
  case when z.stock_hoy < z.stock_minimo * (select valor::numeric from config where parametro = 'factor_stock_urgente') then 'URGENTE'
       when z.stock_hoy < z.stock_minimo then 'BAJO MÍNIMO' else 'AL DÍA' end as estado_hoy,
  case when z.proyectado < 0 then 'FALTARÁ' when z.proyectado < z.stock_minimo then 'BAJO MÍNIMO' else 'AL DÍA' end as estado_proyectado
from (
  select r.id_repuesto, r.nombre, r.tipo, r.stock_actual as stock_hoy, r.stock_minimo,
    coalesce((select sum(greatest(o.cantidad_plan - coalesce((select sum(u.cantidad) from uso_repuestos u where u.ot = o.ot and u.id_repuesto = o.id_repuesto), 0), 0))
              from ordenes_trabajo o where o.id_repuesto = r.id_repuesto and o.estado <> 'Completada'), 0)::int as consumo_programado,
    coalesce((select sum(cantidad) from compras c where c.id_repuesto = r.id_repuesto and c.estado = 'Aprobada'), 0)::int as en_camino,
    r.stock_actual - coalesce((select sum(greatest(o.cantidad_plan - coalesce((select sum(u.cantidad) from uso_repuestos u where u.ot = o.ot and u.id_repuesto = o.id_repuesto), 0), 0))
              from ordenes_trabajo o where o.id_repuesto = r.id_repuesto and o.estado <> 'Completada'), 0)
      + coalesce((select sum(cantidad) from compras c where c.id_repuesto = r.id_repuesto and c.estado = 'Aprobada'), 0) as proyectado,
    case when public.mp_rol() = 'Jefe' then r.stock_actual * coalesce(r.precio_unitario_clp, 0) end as valor_en_stock_clp
  from repuestos r where r.controla_stock = 'Sí'
) z;

-- Capa de reportes (alimenta el Informe mensual de costos; solo Jefe)
create or replace view rep_gasto_mensual_equipo with (security_invoker = true) as
select v.mes_clave, v.codigo_equipo, e.nombre as equipo, sum(v.cantidad) as repuestos_uds, sum(v.subtotal_clp) as gasto_clp
from vista_uso v join equipos e on e.codigo_equipo = v.codigo_equipo
where public.mp_rol() = 'Jefe'
group by v.mes_clave, v.codigo_equipo, e.nombre;

create or replace view rep_gasto_mensual_repuesto with (security_invoker = true) as
select v.mes_clave, v.repuesto, sum(v.cantidad) as unidades, sum(v.subtotal_clp) as gasto_clp
from vista_uso v
where public.mp_rol() = 'Jefe'
group by v.mes_clave, v.repuesto;

create or replace view rep_mantenciones_mes with (security_invoker = true) as
select to_char(o.fecha_termino at time zone 'America/Santiago', 'YYYYMM')::int as mes_clave, o.codigo_equipo, count(*) as mantenciones
from ordenes_trabajo o
where o.estado = 'Completada' and public.mp_rol() = 'Jefe'
group by 1, 2;

create or replace view rep_compras_mes_origen with (security_invoker = true) as
select to_char(c.fecha_hora at time zone 'America/Santiago', 'YYYYMM')::int as mes_clave, c.origen,
       count(*) as ordenes, sum(c.cantidad * coalesce(c.precio_unitario_clp, 0)) as monto_clp
from compras c
where public.mp_rol() = 'Jefe'
group by 1, 2;

