  foreach t in array array['cat_ubicaciones','cat_categorias','cat_tipos_trabajo','cat_estados_fisicos','config'] loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists %I on %I', t||'_sel', t);
    execute format('drop policy if exists %I on %I', t||'_mod', t);
    execute format('create policy %I on %I for select to authenticated using (public.mp_rol() is not null)', t||'_sel', t);
    execute format('create policy %I on %I for all to authenticated using (public.mp_rol() = ''Jefe'') with check (public.mp_rol() = ''Jefe'')', t||'_mod', t);
