    execute format('drop policy if exists %I on %I', t||'_upd', t);
    execute format('drop policy if exists %I on %I', t||'_del', t);
    execute format('create policy %I on %I for select to authenticated using (public.mp_rol() is not null)', t||'_sel', t);
    execute format('create policy %I on %I for insert to authenticated with check (public.mp_rol() is not null)', t||'_ins', t);
    execute format('create policy %I on %I for update to authenticated using (public.mp_rol() is not null) with check (public.mp_rol() is not null)', t||'_upd', t);
    execute format('create policy %I on %I for delete to authenticated using (public.mp_rol() = ''Jefe'')', t||'_del', t);
  end loop;
